# Подключаем библиотеку numpy для работы с матрицами
# Импортируем функцию det для вычисления определителей
import numpy as np
from numpy.linalg import det

# Задание 1
print("=" * 50)
print("ЗАДАНИЕ 1")
print("=" * 50)

# Задаём матрицу коэффициентов A (3 строки, 3 столбца)
# Первое уравнение: 1*x1 + 2*x2 - 1*x3 = 7
# Второе уравнение: 2*x1 - 3*x2 + 1*x3 = 3
# Третье уравнение: 1*x1 + 1*x2 - 1*x3 = 16
A1 = np.array([[1, 2, -1],
               [2, -3, 1],
               [1, 1, -1]], dtype=float)
# Задаём вектор правой части b
b1 = np.array([7, 3, 16], dtype=float)

# Способ 1: функция solve
# solve решает систему A*x = b напрямую, без вычисления обратной матрицы
print("Способ 1: функция solve")
x_solve1 = np.linalg.solve(A1, b1)
# Выводим результат
print("x1 =", x_solve1[0])
print("x2 =", x_solve1[1])
print("x3 =", x_solve1[2])

# Способ 2: метод Крамера
# Метод Крамера: x_i = det(A_i) / det(A), где A_i - матрица A с заменой i-го столбца на b
print("\nСпособ 2: метод Крамера")

# Вычисляем главный определитель системы
detA1 = det(A1)

# Для x1: заменяем первый столбец на b
# Было: [1, 2, -1] -> стало: [7, 3, 16]
A1_x1 = np.array([[b1[0], 2, -1],
                  [b1[1], -3, 1],
                  [b1[2], 1, -1]], dtype=float)

# Для x2: заменяем второй столбец на b
A1_x2 = np.array([[1, b1[0], -1],
                  [2, b1[1], 1],
                  [1, b1[2], -1]], dtype=float)

# Для x3: заменяем третий столбец на b
A1_x3 = np.array([[1, 2, b1[0]],
                  [2, -3, b1[1]],
                  [1, 1, b1[2]]], dtype=float)

# Вычисляем x1, x2, x3 по формуле Крамера
x1_cramer = det(A1_x1) / detA1
x2_cramer = det(A1_x2) / detA1
x3_cramer = det(A1_x3) / detA1

# Выводим результат
print("x1 =", x1_cramer)
print("x2 =", x2_cramer)
print("x3 =", x3_cramer)

# Разделитель между заданиями для красоты вывода
print("\n" + "-" * 50)

# Задание 2
# Решаем систему из 5 уравнений с треугольной матрицей
# Матрица имеет верхнетреугольный вид (ниже главной диагонали нули)
print("=" * 50)
print("ЗАДАНИЕ 2")
print("=" * 50)
# Задаём матрицу A (5x5) - верхнетреугольная
# 1*x1 + 1*x2 + 1*x3 + 1*x4 + 1*x5 = 5
# 0*x1 + 2*x2 + 1*x3 + 1*x4 + 1*x5 = 4
# 0*x1 + 0*x2 + 3*x3 + 1*x4 + 1*x5 = 3
# 0*x1 + 0*x2 + 0*x3 + 4*x4 + 1*x5 = 2
# 0*x1 + 0*x2 + 0*x3 + 0*x4 + 5*x5 = 1
A2 = np.array([[1, 1, 1, 1, 1],
               [0, 2, 1, 1, 1],
               [0, 0, 3, 1, 1],
               [0, 0, 0, 4, 1],
               [0, 0, 0, 0, 5]], dtype=float)

# Задаём вектор правой части b
b2 = np.array([5, 4, 3, 2, 1], dtype=float)

# Способ 1: функция solve
print("Способ 1: функция solve")
x_solve2 = np.linalg.solve(A2, b2)

# Выводим результат
print("x1 =", x_solve2[0])
print("x2 =", x_solve2[1])
print("x3 =", x_solve2[2])
print("x4 =", x_solve2[3])
print("x5 =", x_solve2[4])

# Способ 2: обратный ход метода Гаусса
# Для верхнетреугольной матрицы решение начинается с последнего уравнения и идёт вверх (обратный ход)
print("\nСпособ 2: обратный ход метода Гаусса")

# Создаём массив для хранения решения
x_gauss = np.zeros(5)

# Шаг 1: из 5-го уравнения: 5 * x5 = 1, отсюда x5 = 1 / 5
x_gauss[4] = b2[4] / A2[4][4]  # x5 = 0.2

# Шаг 2: из 4-го уравнения: 4*x4 + 1*x5 = 2, отсюда x4 = (2 - x5) / 4
x_gauss[3] = (b2[3] - A2[3][4] * x_gauss[4]) / A2[3][3]  # x4

# Шаг 3: из 3-го уравнения: 3*x3 + 1*x4 + 1*x5 = 3
x_gauss[2] = (b2[2] - A2[2][3] * x_gauss[3] - A2[2][4] * x_gauss[4]) / A2[2][2]  # x3

# Шаг 4: из 2-го уравнения: 2*x2 + 1*x3 + 1*x4 + 1*x5 = 4
x_gauss[1] = (b2[1] - A2[1][2] * x_gauss[2] - A2[1][3] * x_gauss[3] - A2[1][4] * x_gauss[4]) / A2[1][1]  # x2

# Шаг 5: из 1-го уравнения: 1*x1 + 1*x2 + 1*x3 + 1*x4 + 1*x5 = 5
x_gauss[0] = (b2[0] - A2[0][1] * x_gauss[1] - A2[0][2] * x_gauss[2] - A2[0][3] * x_gauss[3] - A2[0][4] * x_gauss[4]) / A2[0][0]  # x1

# Выводим результат
print("x1 =", x_gauss[0])
print("x2 =", x_gauss[1])
print("x3 =", x_gauss[2])
print("x4 =", x_gauss[3])
print("x5 =", x_gauss[4])

print("\n" + "-" * 50)


# Задание 3
# Решаем систему из 5 уравнений с нижнетреугольной матрицей
# Матрица имеет нижнетреугольный вид (выше главной диагонали нули)
print("=" * 50)
print("ЗАДАНИЕ 3")
print("=" * 50)
# Задаём матрицу A (5x5) - нижнетреугольная
# 5*x1 + 0*x2 + 0*x3 + 0*x4 + 0*x5 = 1
# 1*x1 + 5*x2 + 0*x3 + 0*x4 + 0*x5 = 1
# 1*x1 + 1*x2 + 5*x3 + 0*x4 + 0*x5 = 1
# 1*x1 + 1*x2 + 1*x3 + 5*x4 + 0*x5 = 1
# 1*x1 + 1*x2 + 1*x3 + 1*x4 + 5*x5 = 1
A3 = np.array([[5, 0, 0, 0, 0],
               [1, 5, 0, 0, 0],
               [1, 1, 5, 0, 0],
               [1, 1, 1, 5, 0],
               [1, 1, 1, 1, 5]], dtype=float)

# Задаём вектор правой части b
b3 = np.array([1, 1, 1, 1, 1], dtype=float)

# Способ 1: функция solve
print("Способ 1: функция solve")
x_solve3 = np.linalg.solve(A3, b3)

# Выводим результат
print("x1 =", x_solve3[0])
print("x2 =", x_solve3[1])
print("x3 =", x_solve3[2])
print("x4 =", x_solve3[3])
print("x5 =", x_solve3[4])

# Способ 2: последовательное исключение (прямой ход)
# Для нижнетреугольной матрицы решение начинается с первого уравнения и идёт вниз (прямой ход)
print("\nСпособ 2: последовательное исключение переменных")
# Создаём массив для хранения решения
x_seq = np.zeros(5)
# Шаг 1: из 1-го уравнения: 5*x1 = 1, отсюда x1 = 1 / 5 = 0.2
x_seq[0] = b3[0] / A3[0][0]  # x1

# Шаг 2: из 2-го уравнения: 1*x1 + 5*x2 = 1, отсюда x2 = (1 - x1) / 5
x_seq[1] = (b3[1] - A3[1][0] * x_seq[0]) / A3[1][1]  # x2

# Шаг 3: из 3-го уравнения: 1*x1 + 1*x2 + 5*x3 = 1
x_seq[2] = (b3[2] - A3[2][0] * x_seq[0] - A3[2][1] * x_seq[1]) / A3[2][2]  # x3

# Шаг 4: из 4-го уравнения: 1*x1 + 1*x2 + 1*x3 + 5*x4 = 1
x_seq[3] = (b3[3] - A3[3][0] * x_seq[0] - A3[3][1] * x_seq[1] - A3[3][2] * x_seq[2]) / A3[3][3]  # x4

# Шаг 5: из 5-го уравнения: 1*x1 + 1*x2 + 1*x3 + 1*x4 + 5*x5 = 1
x_seq[4] = (b3[4] - A3[4][0] * x_seq[0] - A3[4][1] * x_seq[1] - A3[4][2] * x_seq[2] - A3[4][3] * x_seq[3]) / A3[4][4]  # x5

# Выводим результат
print("x1 =", x_seq[0])
print("x2 =", x_seq[1])
print("x3 =", x_seq[2])
print("x4 =", x_seq[3])
print("x5 =", x_seq[4])