# Импортируем библиотеку numpy для работы с матрицами
import numpy as np

# Задание 1
# Выводим заголовок первого задания для наглядности
print("=" * 50)
print("ЗАДАНИЕ 1")
print("=" * 50)

# Задаём матрицу A из условия задачи (3 строки, 3 столбца)
# dtype=float - указываем, что элементы будут числами с плавающей точкой
A = np.array([[4, -1, 7],
              [0, 1, -2],
              [0, 0, 9]], dtype=float)
# Задаём матрицу B
B = np.array([[-1, 1, 0],
              [0, 0, 3],
              [6, 2, -1]], dtype=float)
# Задаём матрицу C
C = np.array([[5, 1, 1],
              [1, 5, 1],
              [1, 1, 5]], dtype=float)

# Вычисляем B^T (транспонирование матрицы B)
# .T - это свойство numpy, которое возвращает транспонированную матрицу
B_T = B.T

# Вычисляем A^T (транспонирование матрицы A)
A_T = A.T

# Вычисляем M1 = A + 3 * B^T
# Умножение матрицы на число: каждый элемент умножается на 3
M1 = A + 3 * B_T

# Вычисляем M2 = 3 * A^T - B
M2 = 3 * A_T - B

# Вычисляем M = M1 * M2 (матричное умножение)
# np.dot() выполняет матричное умножение (не поэлементное!)
M = np.dot(M1, M2)

# Решаем матричное уравнение M * X = C
# np.linalg.solve() решает систему линейных уравнений
X = np.linalg.solve(M, C)

# Выводим результат - матрицу X
print("Матрица X (решение уравнения):")
print(X)

# Проверка: вычисляем M * X и выводим на экран
# Должно получиться C (с небольшой погрешностью из-за округлений)
print("\nПроверка (M * X должно равняться C):")
print(np.dot(M, X))

# Разделитель между заданиями для красоты вывода
print("\n" + "-" * 50)


