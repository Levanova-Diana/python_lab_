# Задаём матрицу B
B = np.array([[-1, 0, 0],
              [1, -3, 0],
              [1, 1, -5]], dtype=float)
# Вычисляем A^2
A2 = np.linalg.matrix_power(A, 2)
# Вычисляем A^3
A3 = np.linalg.matrix_power(A, 3)
# Вычисляем A^3 - 2*A^2 + 3*A
# Это матричный многочлен
M_T = A3 - 2 * A2 + 3 * A
# Транспонируем результат (по условию задачи)
M = M_T.T
# Вычисляем B^2
B2 = np.linalg.matrix_power(B, 2)
# Вычисляем правую часть: 4*B^2 - B
P = 4 * B2 - B
# Решаем уравнение M * X = P
X = np.linalg.solve(M, P)
# Выводим результат
print("Матрица X (решение уравнения):")
print(X)

# Проверка: M * X должно равняться P
print("\nПроверка (M * X должно равняться 4B^2 - B):")
print(np.dot(M, X))