# Задаём матрицу A
A = np.array([[-1, 2, -4],
              [1, -1, 7],
              [-1, 0, 0]], dtype=float)
# Задаём матрицу B
B = np.array([[1, 0, 0],
              [0, 2, 0],
              [1, 0, 3]], dtype=float)
# Задаём матрицу C
C = np.array([[3, 8, -1],
              [0, 8, 0],
              [2, -1, 3]], dtype=float)

# Вычисляем A^2 - матрица, умноженная сама на себя
# matrix_power() возводит матрицу в заданную степень
A2 = np.linalg.matrix_power(A, 2)
# Вычисляем B^3
B3 = np.linalg.matrix_power(B, 3)
# Вычисляем A^2 * B (матричное умножение)
term1 = np.dot(A2, B)
# Вычисляем B^3 * A (матричное умножение)
term2 = np.dot(B3, A)
# Складываем: A^2 * B + B^3 * A
M_T = term1 + term2
# Транспонируем результат - получаем матрицу M перед X
# По условию: (A^2*B + B^3*A)^T * X = BC
M = M_T.T
# Вычисляем правую часть: B * C
P = np.dot(B, C)
# Решаем уравнение M * X = P
X = np.linalg.solve(M, P)
# Выводим результат
print("Матрица X (решение уравнения):")
print(X)

# Проверка: M * X должно равняться P
print("\nПроверка (M * X должно равняться B*C):")
print(np.dot(M, X))

print("\n" + "-" * 50)


